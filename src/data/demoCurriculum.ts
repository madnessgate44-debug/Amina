/**
 * Helper to get a flat array of all 54 concepts with their hierarchy context
 */
export function getFlatCurriculumConcepts(): FlatCurriculumConcept[] {
  const result: FlatCurriculumConcept[] = [];

  for (const subject of DEMO_CURRICULUM) {
    for (const unit of subject.units) {
      for (const lesson of unit.lessons) {
        for (const concept of lesson.concepts) {
          result.push({
            id: concept.id,
            parentId: lesson.id,
            subjectId: subject.id,
            subjectNameAr: subject.nameAr,
            subjectNameEn: subject.nameEn,
            unitId: unit.id,
            unitNameAr: unit.nameAr,
            unitNameEn: unit.nameEn,
            lessonId: lesson.id,
            lessonNameAr: lesson.nameAr,
            lessonNameEn: lesson.nameEn,
            nameAr: concept.nameAr,
            nameEn: concept.nameEn,
            descriptionAr: concept.descriptionAr,
            descriptionEn: concept.descriptionEn,
            origin: concept.origin,
          });
        }
      }
    }
  }

  return result;
}

/**
 * Lookup single concept by ID
 */
export function findConceptById(conceptId: string): CurriculumConcept | null {
  for (const subject of DEMO_CURRICULUM) {
    for (const unit of subject.units) {
      for (const lesson of unit.lessons) {
        const found = lesson.concepts.find((c) => c.id === conceptId);
        if (found) return found;
      }
    }
  }
  return null;
}

